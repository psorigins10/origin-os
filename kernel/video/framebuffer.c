static void put_pixel(
    uint32_t x,
    uint32_t y,
    uint32_t color
)
{
    if (g_fb == 0)
        return;

    if (x >= g_fb->fb_width || y >= g_fb->fb_height)
        return;

    volatile uint32_t *fb =
        (volatile uint32_t *)(uintptr_t)g_fb->fb_base;

    fb[y * g_fb->fb_pixels_per_scanline + x] = color;
}


static void draw_char(
    char c,
    uint32_t x,
    uint32_t y,
    uint32_t scale,
    uint32_t color
)
{
    if ((unsigned char)c >= 128)
        return;

    const uint8_t *g = font[(unsigned char)c];

    for (uint32_t row = 0; row < 8; row++) {

        for (uint32_t col = 0; col < 8; col++) {

            if (g[row] & (0x80 >> col)) {

                for (uint32_t dy = 0; dy < scale; dy++) {

                    for (uint32_t dx = 0; dx < scale; dx++) {

                        put_pixel(
                            x + col * scale + dx,
                            y + row * scale + dy,
                            color
                        );
                    }
                }
            }
        }
    }
}


void framebuffer_init(ORIGIN_BOOT_INFO *boot_info)
{
    g_fb = boot_info;
}


void framebuffer_clear(uint32_t color)
{
    if (g_fb == 0)
        return;

    for (uint32_t y = 0; y < g_fb->fb_height; y++) {

        for (uint32_t x = 0; x < g_fb->fb_width; x++) {

            put_pixel(x, y, color);
        }
    }
}


void framebuffer_draw_string(
    const char *string,
    uint32_t x,
    uint32_t y,
    uint32_t scale,
    uint32_t color
)
{
    if (string == 0)
        return;

    if (scale == 0)
        return;

    for (; *string != '\0'; string++) {

        draw_char(
            *string,
            x,
            y,
            scale,
            color
        );

        x += 8 * scale;
    }
}